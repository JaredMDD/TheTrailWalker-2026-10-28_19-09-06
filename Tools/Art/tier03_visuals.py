"""Shared by the Tier 3 integration staging scripts: regenerate Assets/_Game/Scripts/Unity/Tier3Visuals.cs from every
Assets/_Game/Art/Tier03/Tier03Slice*Manifest.json. Only display rows (Role absent or "Display") become item lookups;
worn fits bind through the wearable art map instead. Standard library only."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[2]
ART = ROOT / 'Assets/_Game/Art/Tier03'
VISUALS = ROOT / 'Assets/_Game/Scripts/Unity/Tier3Visuals.cs'


def manifests():
    return sorted(ART.glob('Tier03Slice*Manifest.json'))


def write_visuals():
    pairs = []
    for m in manifests():
        for r in json.loads(m.read_text(encoding='utf-8'))['Items']:
            if r.get('Role', 'Display') == 'Display':
                pairs += [(i, r['PrefabPath']) for i in r['ItemIds']]
    ids = [i for i, _ in pairs]
    if len(ids) != len(set(ids)):
        raise SystemExit('An item id is bound twice across the slice manifests')
    pairs.sort()
    sources = ', '.join(m.name for m in manifests())
    lines = ['// <auto-generated> by Tools/Art/tier03_visuals.py (run through the stage_tier03_slice_*.py scripts) from ' + sources + '.',
             '// Do not edit by hand; rerun a staging script.',
             'using System.Collections.Generic;', '', 'namespace TheTrailWalker', '{',
             '    // Resources paths for tier 3 item models (Tier 3 settlement integration).',
             '    public static class Tier3Visuals', '    {',
             '        private static readonly Dictionary<string, string> Paths = new Dictionary<string, string>', '        {']
    lines += [f'            {{ "{i}", "{p}" }},' for i, p in pairs]
    lines += ['        };', '',
              '        public static string PathFor(string itemId) => itemId != null && Paths.TryGetValue(itemId, out string path) ? path : null;',
              '        public static bool Has(string itemId) => itemId != null && Paths.ContainsKey(itemId);',
              '        public static IEnumerable<KeyValuePair<string, string>> All => Paths;',
              '    }', '}', '']
    VISUALS.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    return len(pairs)
