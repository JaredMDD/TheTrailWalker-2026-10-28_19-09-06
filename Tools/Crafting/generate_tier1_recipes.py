"""Generates Assets/_Game/Scripts/Domain/Crafting/Tier1Recipes.cs from the tier-one recipe catalog JSON.

Run from the project root: python Tools/Crafting/generate_tier1_recipes.py
"""
import json
import os

SOURCE = "Assets/_Game/Art/Crafting/Tier01/Tier01Recipes.json"
TARGET = "Assets/_Game/Scripts/Domain/Crafting/Tier1Recipes.cs"


def cs(text):
    return text.replace("\\", "\\\\").replace('"', '\\"')


def main():
    with open(SOURCE, encoding="utf-8") as handle:
        catalog = json.load(handle)
    lines = []
    for recipe in catalog["Recipes"]:
        inputs = ", ".join(f'new RecipeInput("{i["ItemId"]}", {i["Quantity"]})' for i in recipe["Inputs"])
        retired = ", retired: true" if recipe.get("Retired") else ""
        lines.append(
            f'            new RecipeDefinition("{recipe["Id"]}", "{cs(recipe["Name"])}", RecipeRole.{recipe["Category"]}, {recipe["Tier"]}, '
            f'"{recipe["OutputId"]}", {recipe["Yield"]}, {float(recipe["BaseSeconds"])}f, "{cs(recipe["UnlockSource"])}", new[] {{ {inputs} }}{retired}),')
    text = (
        "// Generated by Tools/Crafting/generate_tier1_recipes.py from " + SOURCE + "\n"
        "// (tier-one recipe catalog). Regenerate rather than editing by hand. Catalog entries do not grant recipe knowledge.\n"
        "namespace TheTrailWalker.Domain.Crafting\n{\n    public static class Tier1Recipes\n    {\n"
        "        public static readonly RecipeDefinition[] All = {\n" + "\n".join(lines) + "\n        };\n    }\n}\n")
    os.makedirs(os.path.dirname(TARGET), exist_ok=True)
    with open(TARGET, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print(f"{len(lines)} recipes -> {TARGET}")


if __name__ == "__main__":
    main()
